#!/usr/bin/env python3
"""Writes conversion_validation.md from the per-instance conversion checks (<txt>/<problem>/conversion_check.json
and meta.json, produced by sdpa_to_cuadmm.py and check_conversion.py), plus data/conversion_checks.csv."""
import csv, json, os

EXP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TXT = os.path.expanduser('~/cuadmm-data/plato_kocvara/txt')
CL = {r['problem']: r for r in csv.DictReader(open(os.path.join(EXP, 'data', 'clarabel_reference.csv')))}
rows = []
for name in sorted(os.listdir(TXT)):
    p = os.path.join(TXT, name, 'conversion_check.json')
    if not os.path.exists(p):
        continue
    j, meta = json.load(open(p)), json.load(open(os.path.join(TXT, name, 'meta.json')))
    c = j['checks']
    rk = c['full_row_rank']
    det = rk['detail'] if isinstance(rk['detail'], dict) else {}
    rows.append(dict(problem=name, all_ok=j['all_ok'], blocks_ok=c['blocks']['ok'], con_num_ok=c['con_num']['ok'], indices_ok=c['largest_indices']['ok'],
                     b_equals_c=c['b_equals_c']['ok'], forward_worst_rel=c['forward_inner_products']['detail']['worst_relative'],
                     objective_worst_rel=c['objective_matrix']['detail']['worst_relative'], adjoint_worst_rel=c['adjoint']['detail']['worst_relative'],
                     round_trip_worst_rel=c['round_trip']['detail']['worst_relative'], round_trip_missing=c['round_trip']['detail']['missing_entries'],
                     rank=det.get('rank', ''), m=meta['m'], cond_AAt=det.get('condition', ''),
                     rank_note='' if det else str(rk['detail']), zeros_dropped=meta['zeros_dropped'], lower_mirrored=meta['lower_mirrored'],
                     duplicates=meta['duplicates'], nonfinite=meta['nonfinite'], n_1x1_psd_as_l=meta['n_1x1_psd_blocks'],
                     clarabel_rel_diff_to_published=CL[name]['rel_diff'] if name in CL else ''))
with open(os.path.join(EXP, 'data', 'conversion_checks.csv'), 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)
g = lambda x: f'{float(x):.1e}' if x != '' else ''
L = ['# Conversion validation: SDPA (.dat-s) to the cuADMM TXT format', '',
     'Converter `scripts/sdpa_to_cuadmm.py`, independent checker `scripts/check_conversion.py` (a separate SDPA reader, it does not import the converter), '
     'driver `scripts/convert_all.sh`, logs in `logs/conversion/`. Generated by `scripts/conversion_summary.py`; the numbers are in `data/conversion_checks.csv`.', '',
     '## Mapping', '',
     'SDPA primal (Mittelmann/SDPA convention): max tr(F0 Y) s.t. tr(F_i Y) = c_i, Y psd; dual min c^T x s.t. sum_i x_i F_i - F0 = X psd. '
     'cuADMM solves min <C, X> s.t. A(X) = b, X in K. The converter sets C = -F0, A_i = F_i, b = c, so that X_cuADMM = Y_SDPA, '
     'y_cuADMM = -x_SDPA, S_cuADMM = X_SDPA, and the SDPA objective is -<C, X>. Negative SDPA block sizes (diagonal blocks) become `l` blocks; '
     'a 1 x 1 PSD block is stored as `l 1` (the same cone) and recorded as `s` in `dimacs_blocks.txt`, which the DIMACS norms use. '
     'Matrices are stored as svec (upper triangle, column major, index j(j+1)/2 + i, off-diagonal entries times sqrt 2).', '',
     'The orientation and sign are confirmed independently: Clarabel (interior point, not MOSEK) solves the converted data, and -<C, X*> equals the published '
     'objective (after the scale factors of `accuracy_protocol.md` section 4); see `data/clarabel_reference.csv`.', '',
     '## Checks', '',
     '1. structure: block sizes and kinds against the SDPA header, vec_len, con_num, largest indices; b equals the SDPA c vector;',
     '2. forward: for 3 random block-diagonal symmetric Y, <F_k, Y> from the full symmetric definition equals (A svec(Y))_k, and <F_0, Y> = -C . svec(Y);',
     '3. adjoint: for 3 random w, the upper triangle of sum_k w_k F_k - F_0 equals svec^-1(A^T w + C);',
     '4. round trip: the TXT data written back to SDPA and re-read reproduce every original entry;',
     '5. rank: A A^T is positive definite (dense eigenvalues) when m <= 6000; for mater-5 and mater-6 (m = 10,143 and 20,463) the rank comes from the '
     'CHOLMOD factorization report of cuADMM (no tiny or non-positive pivots; recorded in every run summary as aat_tiny_pivots and aat_nonpositive_pivots);',
     '6. input hygiene: no explicit duplicates, no non-finite values; explicit zeros dropped and lower-triangle entries mirrored are counted.', '',
     '## Results (tolerance 1e-12 relative for checks 2-4)', '',
     '| problem | all checks | forward | objective | adjoint | round trip | rank / m | cond(A A^T) | zeros dropped | 1x1 PSD as l |',
     '|---|---|---|---|---|---|---|---|---|---|']
for r in rows:
    L.append(f"| {r['problem']} | {'pass' if r['all_ok'] else 'FAIL'} | {g(r['forward_worst_rel'])} | {g(r['objective_worst_rel'])} | {g(r['adjoint_worst_rel'])} | "
             f"{g(r['round_trip_worst_rel'])} | {str(r['rank']) + ' / ' + str(r['m']) if r['rank'] != '' else 'CHOLMOD (m = ' + str(r['m']) + ')'} | "
             f"{g(r['cond_AAt'])} | {r['zeros_dropped']} | {r['n_1x1_psd_as_l']} |")
L += ['', f"{sum(r['all_ok'] for r in rows)} of {len(rows)} instances pass every check; no instance is CONVERSION_FAILED."]
open(os.path.join(EXP, 'conversion_validation.md'), 'w').write('\n'.join(L) + '\n')
print(f"{sum(r['all_ok'] for r in rows)}/{len(rows)} pass")
